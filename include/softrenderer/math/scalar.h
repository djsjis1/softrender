#pragma once

// ============================================================
// 标量数学工具
//
// 为什么单独成头：着色器里有大量「固定指数」的幂运算。std::pow 是库函数
// （每次约 13 ns），而固定小整数次幂展开成几次乘法就能完成，在逐片元的
// 路径上差别可观。动态指数（shininess）仍必须用 std::pow。
// ============================================================

namespace sr
{

// x 的 5 次方。Fresnel-Schlick 近似固定用 5 次幂。
// 与 std::pow(x, 5) 在 [0,1] 上最大差 < 1e-7（由单测锁定）。
inline float pow5(float x)
{
    const float x2 = x * x;
    return x2 * x2 * x;
}

} // namespace sr
